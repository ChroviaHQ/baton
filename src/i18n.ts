const isZh = navigator.language.toLowerCase().startsWith('zh');
export const t: Messages = isZh ? zh : en;
document.documentElement.lang = isZh ? 'zh-CN' : 'en';

function describeDetail(detail: string): string {
  const reason = detail.replace(/^hop \d+ failed: /, '');
  const socks5 = reason.match(/^proxy answered SOCKS5 reply 0x([0-9a-f]{2})$/);
  if (socks5) {
    return t.socks5Replies[parseInt(socks5[1], 16)] || reason;
  }
  return reason.replace(/^proxy answered /, '');
}

export function describeError(error: CommandError): string {
  const hopName = error.hop === null ? '' : t.hopNames[error.hop] ?? '';
  const template = t.errors[error.code] ?? t.errors.unknown;
  return template.replace('{hop}', hopName).replace('{detail}', describeDetail(error.detail));
}
